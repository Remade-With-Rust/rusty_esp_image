#!/usr/bin/env python3
"""Turn an esp32-camera `<sensor>_settings.h` into a Rust module of register
tables as data — the converter the OV2640 and OV5640 modules were made with,
now checked in.

    python tools/convert-sensor-tables.py ov3660 <ov3660_settings.h> <component version> [<ov3660_regs.h> ...] > crates/rusty_esp_image-core/src/sensor/ov3660.rs

Macro names are resolved to their values (the settings header's own and
those of any register-name headers given after the version), the list
terminators dropped, and nothing else is changed. Delay steps (`REG_DLY`)
become `RegOp::DelayMs`. The aspect-ratio table, when the header has one,
becomes `RATIO_TABLE`.
"""
import re
import sys

# the output is Rust source, UTF-8 whatever the console's code page
sys.stdout.reconfigure(encoding="utf-8")
sensor, path, version = sys.argv[1], sys.argv[2], sys.argv[3]
src = open(path, encoding="utf-8", errors="replace").read()

# the headers' macros: REG_DLY, REGLIST_TAIL, BANK_SEL, the register names
macros = {}
for header in [path] + sys.argv[4:]:
    text = open(header, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r"^#define\s+(\w+)\s+((?:0x)?[0-9a-fA-F]+)\b", text, re.M):
        macros[m.group(1)] = int(m.group(2), 0)
# esp32-camera's shared names
macros.setdefault("REG_DLY", 0xFFFF)
macros.setdefault("REGLIST_TAIL", 0x0000)
macros.setdefault("BANK_SEL", 0xFF)
macros.setdefault("BANK_DSP", 0)
macros.setdefault("BANK_SENSOR", 1)


def value(tok):
    tok = tok.strip()
    if tok in macros:
        return macros[tok]
    if re.fullmatch(r"(0x)?[0-9a-fA-F]+", tok):
        return int(tok, 0)
    # a small expression of macros and numbers, e.g. (A | B)
    expr = re.sub(r"\b\w+\b", lambda mm: str(macros.get(mm.group(0), mm.group(0))), tok)
    return int(eval(expr, {"__builtins__": {}}))  # noqa: S307 - header-controlled


def rust_name(c_name):
    n = c_name
    for prefix in (f"{sensor}_settings_", f"{sensor}_", "sensor_"):
        if n.startswith(prefix):
            n = n[len(prefix):]
            break
    return n.upper()


out = []
out.append(f"//! {sensor.upper()} register tables ({'16' if sensor in ('ov3660', 'ov5640') else '8'}-bit registers).")
out.append("//!")
out.append("//! Register tables derived mechanically from `espressif/esp32-camera`")
out.append(f"//! `sensors/private_include/{sensor}_settings.h` at component version {version},")
out.append("//! Copyright 2015-2016 Espressif Systems (Shanghai) PTE LTD, Apache-2.0.")
out.append("//! Macro names were resolved to their values and the list terminators")
out.append("//! dropped; nothing else was changed. See `LICENSE-THIRD-PARTY.md`.")
out.append("//! Generated by `tools/convert-sensor-tables.py`; do not edit by hand.")
out.append("")
out.append("use super::RegOp;")
out.append("")

# the ratio table (OV3660 / OV5640 style)
m = re.search(r"ratio_settings_t\s+ratio_table\[\]\s*=\s*\{(.*?)\};", src, re.S)
if m:
    rows = re.findall(r"\{\s*([^{}]*?)\s*\}\s*,?\s*//\s*(\S+)", m.group(1))
    out.append("/// `ratio_table` from the source file: the sensor window for each aspect")
    out.append("/// ratio — max width and height, start x/y, end x/y, offset x/y, total x/y.")
    out.append("pub const RATIO_TABLE: &[RatioSettings] = &[")
    for body, tag in rows:
        nums = [int(x.strip()) for x in body.split(",")]
        out.append(f"    // {tag}")
        out.append("    RatioSettings {")
        for name, v in zip(["max_width", "max_height", "start_x", "start_y", "end_x", "end_y", "offset_x", "offset_y", "total_x", "total_y"], nums):
            out.append(f"        {name}: {v},")
        out.append("    },")
    out.append("];")
    out.append("")
    out.append("/// One row of [`RATIO_TABLE`].")
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    out.append("pub struct RatioSettings {")
    for name in ["max_width", "max_height", "start_x", "start_y", "end_x", "end_y", "offset_x", "offset_y", "total_x", "total_y"]:
        out.append(f"    /// `{name}` in the source.")
        out.append(f"    pub {name}: u16,")
    out.append("}")
    out.append("")

# every register list: `static const ... uint16_t NAME[][2] = { ... };`
for m in re.finditer(r"static\s+const\s+(?:DRAM_ATTR\s+)?uint(?:8|16)_t\s+(\w+)\[\]\[2\]\s*=\s*\{(.*?)\};", src, re.S):
    name, body = m.group(1), m.group(2)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    pairs = re.findall(r"\{\s*([^{},]+?)\s*,\s*([^{},]+?)\s*\}", body)
    steps = []
    for a, b in pairs:
        addr, val = value(a), value(b)
        if addr == macros["REGLIST_TAIL"] and val == 0:
            break
        if addr == macros["REG_DLY"]:
            steps.append(("delay", val))
        else:
            steps.append(("write", addr, val))
    out.append(f"/// `{name}` from the source file ({len(steps)} steps).")
    out.append(f"pub const {rust_name(name)}: &[RegOp] = &[")
    for s in steps:
        if s[0] == "delay":
            out.append(f"    RegOp::DelayMs({s[1]}),")
        else:
            width = 4 if sensor in ("ov3660", "ov5640") else 2
            out.append("    RegOp::Write {")
            out.append(f"        addr: 0x{s[1]:0{width}X},")
            out.append(f"        value: 0x{s[2]:02X},")
            out.append("    },")
    out.append("];")
    out.append("")

sys.stdout.write("\n".join(out).rstrip("\n") + "\n")
